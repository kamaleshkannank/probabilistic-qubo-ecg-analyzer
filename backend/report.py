def build_pdf(payload: dict) -> bytes:
    buf = io.BytesIO()
    doc = BaseDocTemplate(buf, leftMargin=14 * mm, rightMargin=14 * mm,
                          topMargin=20 * mm, bottomMargin=16 * mm,
                          showBoundary=0)
    
    LAND = landscape(A4)
    
    # Frames for Portrait and Landscape orientations
    frame_p = Frame(14 * mm, 16 * mm,
                    A4[0] - 28 * mm,
                    A4[1] - 36 * mm, id="portrait")
    
    frame_l = Frame(14 * mm, 16 * mm,
                    LAND[0] - 28 * mm,
                    LAND[1] - 36 * mm, id="landscape")
    
    doc.addPageTemplates([
        PageTemplate(id="portrait", frames=[frame_p], pagesize=A4, onPage=lambda c, d: c.setPageSize(A4)),
        PageTemplate(id="landscape", frames=[frame_l], pagesize=LAND, onPage=lambda c, d: c.setPageSize(LAND))
    ])
    
    styles = getSampleStyleSheet()
    
    # Custom Paragraph Styles matching Hospital Theme
    body_style = ParagraphStyle('CardioBody', parent=styles["Normal"], fontSize=8.5, leading=12, textColor=COLOR_DARK_TEXT)
    subhead_style = ParagraphStyle('CardioSub', parent=styles["Normal"], fontSize=9, leading=13, textColor=COLOR_SECONDARY_GRAY)

    story = []
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    pat = payload.get("patient", {}) or {}
    meta = payload.get("meta", {}) or {}
    feat = payload.get("features", {}) or {}
    probs = payload.get("probabilities", []) or []
    fs = meta.get("fs") or feat.get("fs")
    n_samples = meta.get("n_samples")
    dur = f"{n_samples / fs:.1f} s" if n_samples and fs else "Not available"
    fs_txt = f"{fs} Hz" if fs else "Not available"

    # ---------- PAGE 1: clinical summary + conclusion (PORTRAIT) ----------
    story.append(_hdr("ECG ANALYSIS REPORT", styles, size=15))
    story.append(Paragraph("Probabilistic Randomized QUBO-Based ECG Analyzer", subhead_style))
    story.append(Paragraph("<b>RESEARCH PROTOTYPE - CLINICIAN REVIEW REQUIRED</b>", ParagraphStyle('Notice', parent=body_style, textColor=COLOR_CLINICAL_BLUE, fontName="Helvetica-Bold")))
    story.append(Spacer(1, 6))
    
    story.append(_hdr("PATIENT INFORMATION", styles))
    cell_p = lambda text: Paragraph(str(text), body_style)
    story.append(_plain_table(
        [[cell_p("<b>Patient ID</b>"), cell_p(_val(pat, "patient_id")), cell_p("<b>Patient name</b>"), cell_p(_val(pat, "patient_name"))],
         [cell_p("<b>Age</b>"), cell_p(_val(pat, "age")), cell_p("<b>Sex</b>"), cell_p(_val(pat, "sex"))]],
        [30 * mm, 62 * mm, 30 * mm, 60 * mm]))
    
    story.append(Spacer(1, 6))
    story.append(_hdr("ECG INFORMATION", styles))
    story.append(_plain_table(
        [[cell_p("<b>ECG record ID</b>"), cell_p(_val(pat, "record_id") if _val(pat, "record_id") != "Not available" else str(meta.get("record", "Not available"))),
          cell_p("<b>Data source</b>"), cell_p(str(meta.get("source", meta.get("dataset", "Not available")))[:58])],
         [cell_p("<b>Analysis date/time</b>"), cell_p(now), cell_p("<b>Recording window</b>"), cell_p(dur)],
         [cell_p("<b>Sampling frequency</b>"), cell_p(fs_txt), cell_p("<b>Signal quality</b>"), cell_p(str((meta.get("sqi") or {}).get("quality", "Not available")))]],
        [30 * mm, 62 * mm, 30 * mm, 60 * mm]))
    
    story.append(Spacer(1, 8))
    story.extend(_conclusion_block(clinical.conclusion(probs), styles))
    
    # ---------- PAGE 2: full-page waveform (LANDSCAPE / HORIZONTAL) ----------
    story.append(NextPageTemplate("landscape"))
    story.append(PageBreak())
    
    story.append(_hdr("ECG WAVEFORM & BEAT ANNOTATION", styles, size=13))
    img_path = payload.get("waveform_png")
    
    if img_path and os.path.exists(img_path):
        # Full width landscape image (265 mm width x 122 mm height)
        _img = Image(img_path, width=265 * mm, height=122 * mm)
        _img.hAlign = "CENTER"
        story.append(_img)
    else:
        story.append(Paragraph("Waveform image not available.", body_style))
        
    story.append(Spacer(1, 4))
    story.append(Paragraph(
        "<b>Legend:</b> black trace = filtered ECG; numbered markers (R 1..N) = detected R-peaks "
        "(energy detector). No P/QRS/T fiducials drawn.",
        body_style))
    
