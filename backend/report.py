class NumberedCanvas(Canvas):
    """Page X of Y header & footer with dynamic landscape/portrait dimensions."""
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self._header_and_footer(total)
            super().showPage()
        super().save()

    def _header_and_footer(self, total):
        self.saveState()
        w, h = self._pagesize

        # --- Professional Top Header ---
        # Top Accent Lines
        self.setFillColor(COLOR_DEEP_NAVY)
        self.rect(0, h - 4 * mm, w, 4 * mm, fill=True, stroke=False)
        self.setFillColor(COLOR_CLINICAL_BLUE)
        self.rect(0, h - 5 * mm, w, 1 * mm, fill=True, stroke=False)

        # Header Title Left
        self.setFont("Helvetica-Bold", 10)
        self.setFillColor(COLOR_DEEP_NAVY)
        self.drawString(14 * mm, h - 12 * mm, "CARDIOLOGY ECG ANALYSIS REPORT")

        # Subtitle Right
        self.setFont("Helvetica", 8)
        self.setFillColor(COLOR_SECONDARY_GRAY)
        self.drawRightString(w - 14 * mm, h - 12 * mm, "Probabilistic Randomized QUBO ECG Analyzer")

        # Header Divider Rule
        self.setStrokeColor(COLOR_BORDER)
        self.setLineWidth(0.6)
        self.line(14 * mm, h - 15 * mm, w - 14 * mm, h - 15 * mm)

        # --- Professional Bottom Footer ---
        # Footer Divider Rule
        self.line(14 * mm, 14 * mm, w - 14 * mm, 14 * mm)

        # Left: Research Prototype Disclaimer Label
        self.setFont("Helvetica", 7.5)
        self.setFillColor(COLOR_SECONDARY_GRAY)
        self.drawString(14 * mm, 9 * mm, "Research Prototype \u2022 Physician Decision Support \u2022 Clinician Review Required")

        # Right: Page X of Y
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(COLOR_DARK_TEXT)
        self.drawRightString(w - 14 * mm, 9 * mm, f"Page {self._pageNumber} of {total}")

        self.restoreState()


def _hdr(text, styles, size=11):
    style = ParagraphStyle('CustomHeading', parent=styles["Heading2"],
                           fontName='Helvetica-Bold', fontSize=size,
                           leading=size + 4, textColor=COLOR_DEEP_NAVY,
                           spaceBefore=4, spaceAfter=4)
    return Paragraph(text, style)


def _plain_table(rows, widths, size=8.5, header_bg="#0B1F33"):
    t = Table(rows, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(header_bg)),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
        ("FONTSIZE", (0, 0), (-1, -1), size),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, COLOR_LIGHT_GRAY])
    ]))
    return t


def _val(patient: dict, key: str) -> str:
    v = (patient or {}).get(key)
    v = "" if v is None else str(v).strip()
    return v if v else "Not available"


def waveform_png(raw, filtered, fs, r_peaks=(), path="/tmp/ecg_wave.png"):
    """Small dashboard-style plot (kept for API compatibility)."""
    n = min(len(raw), int(10 * fs))
    t = np.arange(n) / fs
    plt.figure(figsize=(10, 3.2))
    plt.plot(t, np.asarray(raw)[:n], lw=0.8, alpha=0.6, label="Raw")
    plt.plot(t, np.asarray(filtered)[:n], lw=1.1, label="Filtered")
    for r in (r_peaks or []):
        if 0 <= r < n:
            plt.axvline(r / fs, color="r", alpha=0.35, lw=0.8)
    plt.xlabel("Time (s)")
    plt.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(path, dpi=110)
    plt.close()
    return path


def waveform_clinical(filtered, fs, r_peaks, units_label, path):
    """Landscape B&W cardiology waveform: black trace, light grid, numbered R-peaks only."""
    x = np.asarray(filtered, dtype=float)
    t = np.arange(len(x)) / fs
    
    # High-resolution landscape ECG trace plot optimized for A4 Landscape full width
    fig, ax = plt.subplots(figsize=(11.5, 4.8), dpi=300)
    fig.patch.set_facecolor("white")
    ax.set_facecolor("white")
    
    ax.plot(t, x, color="#17202A", lw=1.0, zorder=3)
    
    for i, r in enumerate(r_peaks or []):
        if 0 <= r < len(x):
            ax.plot(t[r], x[r], marker="o", color="#1769AA", ms=4.5, zorder=4)
            ax.text(t[r], x[r] + (max(x) - min(x)) * 0.03, f"R{i + 1}", fontsize=6.5,
                    fontweight="bold", color="#0B1F33", ha="center", va="bottom", zorder=5)
            
    ax.set_xlabel("Time (s)", fontsize=9, color="#17202A", fontweight="bold")
    ax.set_ylabel("Amplitude (mV)" if units_label == "mV" else "Signal amplitude (signal units)",
                  fontsize=9, color="#17202A", fontweight="bold")
    
    # Standard Cardiology ECG Grid Lines
    ax.grid(True, which="major", color="#CBD5E1", linestyle="-", linewidth=0.6, alpha=0.8)
    ax.minorticks_on()
    ax.grid(True, which="minor", color="#F1F5F9", linestyle=":", linewidth=0.4, alpha=0.7)
    
    ax.set_xlim(t[0], t[-1])
    for spine in ax.spines.values():
        spine.set_color("#0B1F33")
        spine.set_linewidth(0.8)
        
    plt.tight_layout()
    plt.savefig(path, dpi=300)
    plt.close()
    return path


def _conclusion_block(concl, styles):
    p = concl["primary"]
    d = p.get("detail", {}) or {}
    story = [_hdr("AUTOMATED ECG CONCLUSION", styles)]
    
    body_style = ParagraphStyle('ConclBody', parent=styles["Normal"], fontSize=9, leading=13, textColor=COLOR_DARK_TEXT)
    verdict_style = ParagraphStyle('ConclVerdict', parent=styles["Normal"], fontSize=12, leading=16, textColor=COLOR_CLINICAL_BLUE, fontName="Helvetica-Bold")
    
    story.append(Paragraph(f"{p['verdict']}", verdict_style))
    story.append(Spacer(1, 4))
    if d:
        story.append(Paragraph(
            f"<b>Probability:</b> {d.get('probability', 'n/a')} &nbsp;&nbsp;&nbsp;&nbsp; "
            f"<b>Stability:</b> {d.get('stability', 'n/a')} &nbsp;&nbsp;&nbsp;&nbsp; "
            f"<b>QUBO:</b> {'Selected' if int(d.get('qubo_selected', 0)) == 1 else 'Not selected'}",
            body_style))
        story.append(Spacer(1, 4))
    for b in concl.get("borderline", []):
        story.append(Paragraph(
            f"<b>BORDERLINE CONSIDERATION - {b.get('code', '')}:</b> "
            f"probability={b.get('probability', 'n/a')}, "
            f"stability={b.get('stability', 'n/a')}, "
            f"QUBO={'Selected' if int(b.get('qubo_selected', 0)) == 1 else 'Not selected'}. "
            f"Requires clinician review.", body_style))
    ns = concl.get("not_supported", [])
    if ns:
        story.append(Paragraph("<b>NOT SUPPORTED:</b> " + ", ".join(ns), body_style))
    return story


